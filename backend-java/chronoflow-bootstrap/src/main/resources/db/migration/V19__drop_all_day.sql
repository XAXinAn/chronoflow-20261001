-- 去掉「全天」这个字段（spec §4.1.2）。
--
-- 日程与待办都只有一个时间点，再挂一个 all_day 开关等于给同一个事实两种表达：
-- 界面上会冒出「全天」这个词，接口里还要到处传它，助手也得判断什么时候该置 true。
--
-- 约定（替代这个字段）：时刻落在**当地 00:00** 就表示「只说了哪天、没说几点」，
-- 界面只显示日期、不显示时刻；其余时刻照常显示。存量 all_day=true 的行本来就存的是
-- 当天 00:00，所以语义不变，不需要回填。
ALTER TABLE event DROP COLUMN all_day;
ALTER TABLE task DROP COLUMN all_day;
